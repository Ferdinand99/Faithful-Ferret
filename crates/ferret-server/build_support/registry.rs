//! The generator of the migration registry. `build.rs` runs it on `migrations/`;
//! `tests/schema.rs` runs it on a temporary directory to show that a new file is
//! all that a new migration needs.

use std::fmt::Write as _;
use std::path::Path;

/// Reads `dir` and returns the source of `MIGRATION_FILES`: every `NNNN_name.sql`
/// as `(file name, include_str!(path))`, sorted by name.
///
/// A file that does not match `NNNN_name.sql`, or a number that two files use,
/// is an error: a migration that never runs, or two that race for a position,
/// must stop the build and not surface in production.
pub fn render(dir: &Path) -> Result<String, String> {
    let mut names = Vec::new();
    let entries = std::fs::read_dir(dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    for entry in entries {
        let entry = entry.map_err(|e| format!("{}: {e}", dir.display()))?;
        let name = entry
            .file_name()
            .into_string()
            .map_err(|_| "a migration file name is not UTF-8".to_string())?;
        if !is_migration_name(&name) {
            return Err(format!(
                "{name}: migration files are named NNNN_name.sql (four digits, an underscore, lower-case letters, digits and underscores)"
            ));
        }
        names.push(name);
    }
    names.sort();
    for pair in names.windows(2) {
        if let [a, b] = pair
            && a.get(..4) == b.get(..4)
        {
            return Err(format!("{a} and {b} have the same number"));
        }
    }
    let mut out = String::from(
        "/// Every migration of the server as `(file name, SQL)`, sorted by name.\n\
         /// Generated by build.rs from `migrations/`.\n\
         pub const MIGRATION_FILES: &[(&str, &str)] = &[\n",
    );
    for name in &names {
        let path = dir.join(name);
        let path = path
            .to_str()
            .ok_or_else(|| format!("{name}: the path is not UTF-8"))?;
        // `{:?}` writes a Rust string literal, with the escapes a path may need.
        let _ = writeln!(out, "    ({name:?}, include_str!({path:?})),");
    }
    out.push_str("];\n");
    Ok(out)
}

fn is_migration_name(name: &str) -> bool {
    let Some(stem) = name.strip_suffix(".sql") else {
        return false;
    };
    let Some((number, rest)) = stem.split_once('_') else {
        return false;
    };
    number.len() == 4
        && number.bytes().all(|b| b.is_ascii_digit())
        && !rest.is_empty()
        && rest
            .bytes()
            .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'_')
}
