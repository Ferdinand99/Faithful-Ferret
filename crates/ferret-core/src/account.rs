//! The account flows: create an account, change the master password (and
//! upgrade the KSF profile), recover with the recovery key, and check the
//! recovery key and secret key the user wrote down.
//!
//! Spec: Fase 1 § 4.2 ("Registrering", "Oppgradering av KSF-profil"), § 4.3
//! ("Bytte av MP"), § 4.6, § 6.1 (confirmation at setup) and § 6.3.
//!
//! # What the core does and does not do
//!
//! Every flow is a pure function from what the client has (the OPAQUE
//! registration it has just finished, the vault, the pinned record, the
//! manifest and the wraps the server holds) to the **complete** set of new
//! values for one request. It sends nothing. The signature of the request is
//! made by the caller over the exact bytes it sends: [`PasswordChange::sign`]
//! and [`Recovered::sign`] bind the operation to the flow, so the wrong
//! operation cannot be signed; the body and the nonce come from the caller.
//!
//! The OPAQUE registration is run before the flow, with
//! `opaque_register_start` and `opaque_register_finish`, and the flow takes
//! its [`RegistrationFinished`] by value. The secret key, when the account
//! has one, is generated by the caller **before** the registration, because
//! it is part of the OPAQUE input.
//!
//! # The same checks in every flow
//!
//! Before anything is drawn from the generator, in this order:
//!
//! 1. with a pinned record ([`PinState::Pinned`]): the record is validated;
//!    the OPAQUE server key the registration showed must equal the pinned
//!    one ([`PinnedField::ServerKey`]); the SK bit of the input must equal
//!    the pinned bit; the profile must not be lower than the pinned one
//!    ([`Error::KdfProfileDowngrade`]). **The server key comparison is the
//!    real detection of a changed OPAQUE server key** (plan U19): at login a
//!    changed key only shows up as a failed envelope, but a registration
//!    answers with the key the server holds now. [`PinState::FirstUse`] is
//!    trust on first use and compares nothing;
//! 2. the profile is inside the floor and ceiling;
//! 3. the password must meet the creation floor
//!    ([`OpaqueInput::meets_creation_floor`]): it was made with
//!    `MasterPassword::new`, with 12 characters when a secret key is part of
//!    the input and 15 when not (E8). A password made with `for_unlock` is
//!    refused with `input_too_short`.
//!
//! The estimate of a password strength meter and the blocklist that the
//! design asks for without a secret key are the client's.
//!
//! # Generations
//!
//! A new password or recovery wrap gets `max(pinned floor, generation in the
//! authenticated manifest, generation of the wrap the server holds) + 1`, so
//! a server that rolls the manifest or a wrap back cannot make the client
//! reuse a generation it has seen. A new account starts at 1.
//!
//! # Draws
//!
//! In this order, from `rng`:
//!
//! * [`create_account`]: `VK` (32), `RK` (32), the nonce of the password
//!   wrap (24), the nonce of the recovery wrap (24), the nonce of the
//!   manifest (24);
//! * [`change_password`]: the nonce of the password wrap (24), the nonce of
//!   the manifest (24);
//! * [`recover`]: the nonce of the password wrap (24), the new `RK` (32), the
//!   nonce of the recovery wrap (24), the nonce of the manifest (24).

