/// `method_type` of the password wrap in the manifest. Spec: Fase 1 § 3.1.
const TYPE_PASSWORD: u8 = 1;
/// `method_type` of the recovery wrap in the manifest. Spec: Fase 1 § 3.1.
const TYPE_RECOVERY: u8 = 2;

/// The `seq` of the first checkpoint of a new account. The request that
/// creates the account writes the manifest as the vault's first row, which
/// the server numbers 1.
pub const FIRST_SEQ: u64 = 1;
/// The revision of the first manifest.
pub const FIRST_MANIFEST_REV: u64 = 1;
/// The `kek_generation` of the first wraps.
pub const FIRST_GENERATION: u64 = 1;
/// The first `vk_epoch`.
pub const FIRST_EPOCH: u64 = 1;

fn entries_error() -> Error {
    Error::Malformed(MalformedKind::Entries)
}

fn pinned_record_error() -> Error {
    Error::Malformed(MalformedKind::PinnedRecord)
}

/// The generation after `generation`, within the pinning maximum.
fn after(generation: u64) -> Result<u64, Error> {
    generation
        .checked_add(1)
        .filter(|g| *g <= MAX_GENERATION)
        .ok_or_else(pinned_record_error)
}

/// The ids that the server (or the client) assigns to a new account.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub struct NewAccountIds {
    /// The account, assigned by the server.
    pub account_id: AccountId,
    /// The vault, assigned by the server.
    pub vault_id: VaultId,
    /// The id of the password wrap.
    pub password_method_id: MethodId,
    /// The id of the recovery wrap.
    pub recovery_method_id: MethodId,
}

/// The current manifest row, as the server holds it. It is verified and
/// opened with the vault key before it is used.
#[derive(Clone, Copy, Debug)]
pub struct ManifestRow<'a> {
    /// Its current revision.
    pub rev: u64,
    /// The envelope.
    pub envelope: &'a [u8],
    /// The tag the server stores with it.
    pub tag: &'a [u8; 32],
}

/// A new master password as the client has registered it with OPAQUE: the
/// input it was made from, the finished registration and the profile.
pub struct NewPassword<'a> {
    /// The password input (`mp` or `mp ‖ 0x00 ‖ SK`) that was registered.
    pub input: &'a OpaqueInput,
    /// The finished registration.
    pub registration: RegistrationFinished,
    /// The KSF profile it was registered with.
    pub profile: KsfProfile,
}

/// The checks of the registration against the pinned record and the creation
/// floor. See the module documentation.
fn check_registration(
    pin: PinState<'_>,
    input: &OpaqueInput,
    profile: KsfProfile,
    shown_server_key: &[u8; 32],
) -> Result<(), Error> {
    if let PinState::Pinned(pinned) = pin {
        pinned.validate()?;
        if let Some(key) = &pinned.server_public_key
            && !ct_eq(key, shown_server_key)
        {
            return Err(Error::Pinned(PinnedField::ServerKey));
        }
        if input.includes_secret_key() != pinned.sk_bit {
            return Err(Error::Pinned(PinnedField::SkBit));
        }
        if profile.number() < pinned.ksf_profile {
            return Err(Error::KdfProfileDowngrade);
        }
    }
    check_kdf_params(profile.params())?;
    if !input.meets_creation_floor() {
        return Err(Error::InvalidInput(InputError::TooShort));
    }
    Ok(())
}

/// The index of the one manifest entry of `method_type`.
fn singleton(manifest: &Manifest, method_type: u8) -> Result<usize, Error> {
    let mut found = None;
    for (i, entry) in manifest.methods.iter().enumerate() {
        if entry.method_type == method_type {
            if found.is_some() {
                return Err(entries_error());
            }
            found = Some(i);
        }
    }
    found.ok_or_else(entries_error)
}

fn entry_at(manifest: &Manifest, index: usize) -> Result<&ManifestEntry, Error> {
    manifest.methods.get(index).ok_or_else(entries_error)
}

fn entry_at_mut(manifest: &mut Manifest, index: usize) -> Result<&mut ManifestEntry, Error> {
    manifest.methods.get_mut(index).ok_or_else(entries_error)
}

/// Checks that a wrap opens under `kek` to the vault key of `vault`.
fn check_wrap(
    ctx: &VaultContext,
    kek: &Kek,
    wrap: &WrapRecord,
    vault: &UnlockedVault,
) -> Result<(), Error> {
    let opened = unwrap_vk(ctx, kek, wrap)?;
    if opened.same_vault_key(vault) && opened.auth_public_key() == vault.auth_public_key() {
        Ok(())
    } else {
        Err(Error::Decrypt)
    }
}

// ------------------------------------------------------------ create

/// A new account, complete and checked: it holds secrets (the vault, the
/// recovery key and the secret key), so it has no `Clone` and no `Debug`.
pub struct NewAccount {
    /// The vault, at `vk_epoch` 1.
    pub vault: UnlockedVault,
    /// The recovery key, to be shown once on the emergency sheet.
    pub recovery_key: RecoveryKey,
    /// The secret key that was handed in, to be shown on the sheet.
    pub secret_key: Option<SecretKey>,
    /// The password wrap and the recovery wrap, in that order, both at
    /// generation 1.
    pub wraps: Vec<WrapRecord>,
    /// The manifest, revision 1, with both methods.
    pub manifest: SealedItem,
    /// The first checkpoint, for `seq` [`FIRST_SEQ`], listing the manifest.
    pub checkpoint: Checkpoint,
    /// `pk_a`.
    pub pk_a: [u8; 32],
    /// `pk_r`.
    pub pk_r: [u8; 32],
    /// The OPAQUE registration record to upload (192 bytes).
    pub registration_record: Vec<u8>,
    /// The KSF profile of the registration.
    pub ksf_profile: KsfProfile,
    /// The OPAQUE server public key the registration showed, to pin.
    pub server_public_key: [u8; 32],
}

impl NewAccount {
    /// The pinned record for the device that made the account: the first
    /// epoch, both wraps at generation 1 and the server key of the
    /// registration. `server_url` is at most 512 bytes.
    pub fn pinned(&self, server_url: &str) -> Result<Pinned, Error> {
        if server_url.len() > crate::pinning::MAX_URL_LEN {
            return Err(pinned_record_error());
        }
        Pinned::for_new_account(
            server_url,
            self.vault.context(),
            self.ksf_profile,
            self.secret_key.is_some(),
            self.pk_a,
            self.server_public_key,
            (FIRST_GENERATION, FIRST_GENERATION),
        )
    }
}

/// Makes a new account: a vault key, a recovery key, the password and
/// recovery wraps, the manifest, `pk_a` and `pk_r`, and the first checkpoint.
///
/// `password` is the finished OPAQUE registration of the password input.
/// `sk` is the secret key that went into `input`
/// (generated before the registration), or `None` when `input` has none; it
/// is compared with the end of `input` and a difference is
/// `input_secret_key_mismatch`, so the account cannot be made with a secret
/// key that is not the one in the password. The password must meet the
/// creation floor (see the module documentation).
///
/// The result is checked before it is returned: both wraps open to the vault
/// key, the manifest opens, and the checkpoint verifies against the manifest
/// row.
///
/// Spec: Fase 1 § 4.2 ("Registrering", step 2), § 4.3, § 4.5 and § 6.1.
pub fn create_account<R: SecureRng>(
    rng: &mut R,
    ids: &NewAccountIds,
    password: NewPassword<'_>,
    sk: Option<SecretKey>,
) -> Result<NewAccount, Error> {
    let NewPassword {
        input,
        registration,
        profile,
    } = password;
    check_registration(
        PinState::FirstUse,
        input,
        profile,
        &registration.server_public_key,
    )?;
    let sk_ok = match &sk {
        Some(sk) => input.ends_with_secret_key(sk),
        None => !input.includes_secret_key(),
    };
    if !sk_ok {
        return Err(Error::InvalidInput(InputError::SecretKeyMismatch));
    }
    if ids.password_method_id == ids.recovery_method_id {
        return Err(entries_error());
    }

    let ctx = VaultContext {
        account_id: ids.account_id,
        vault_id: ids.vault_id,
        vk_epoch: FIRST_EPOCH,
    };
    let vault = UnlockedVault::from_vault_key(ctx, VaultKey::generate(rng))?;
    let recovery_key = RecoveryKey::generate(rng);

    let password_kek = Kek::from_export_key(&ids.account_id, &registration.export_key)?;
    let recovery_kek = Kek::from_recovery_key(&ids.account_id, &recovery_key)?;
    let password_wrap = wrap_vk(
        rng,
        &ctx,
        vault.vault_key(),
        &password_kek,
        ids.password_method_id,
        FIRST_GENERATION,
        Method::Password { ksf: profile },
    )?;
    let recovery_wrap = wrap_vk(
        rng,
        &ctx,
        vault.vault_key(),
        &recovery_kek,
        ids.recovery_method_id,
        FIRST_GENERATION,
        Method::Recovery,
    )?;

    let manifest_plain = Manifest::new(
        FIRST_EPOCH,
        vec![
            ManifestEntry::new(TYPE_PASSWORD, ids.password_method_id, FIRST_GENERATION),
            ManifestEntry::new(TYPE_RECOVERY, ids.recovery_method_id, FIRST_GENERATION),
        ],
    );
    let manifest = encrypt_manifest(rng, &vault, FIRST_MANIFEST_REV, &manifest_plain)?;
    let checkpoint = make_checkpoint(
        &vault,
        FIRST_SEQ,
        vec![CheckpointEntry::live(
            ItemId::MANIFEST,
            manifest.rev,
            &manifest.envelope,
        )],
    )?;
    let pk_r = recovery_public_key(&recovery_key, &ids.account_id)?;

    // As a second device would see the new account.
    check_wrap(&ctx, &password_kek, &password_wrap, &vault)?;
    check_wrap(&ctx, &recovery_kek, &recovery_wrap, &vault)?;
    if decrypt_manifest(&vault, manifest.rev, &manifest.envelope, &manifest.tag)? != manifest_plain
    {
        return Err(Error::Decrypt);
    }
    let row = ServerRow::live(
        &vault,
        ItemId::MANIFEST,
        manifest.rev,
        &manifest.envelope,
        &manifest.tag,
    )?;
    verify_checkpoint(&vault, &checkpoint, &[row], FIRST_SEQ)?;

    Ok(NewAccount {
        pk_a: vault.auth_public_key(),
        pk_r,
        vault,
        recovery_key,
        secret_key: sk,
        wraps: vec![password_wrap, recovery_wrap],
        manifest,
        checkpoint,
        registration_record: registration.record,
        ksf_profile: profile,
        server_public_key: registration.server_public_key,
    })
}

// ------------------------------------------------------ change password

/// A new password wrap and manifest, for one `PUT
/// /api/vault/unlock-methods/password` request. Public data only.
#[derive(Clone, PartialEq, Eq, Debug)]
pub struct PasswordChange {
    /// The OPAQUE registration record to upload.
    pub registration_record: Vec<u8>,
    /// The KSF profile of the new registration.
    pub ksf_profile: KsfProfile,
    /// The new password wrap, with `kek_generation` raised.
    pub wrap: WrapRecord,
    /// The new manifest, one revision up, with the new generation.
    pub manifest: SealedItem,
    /// The OPAQUE server public key the registration showed. It has been
    /// compared with the pinned one when there is one.
    pub server_public_key: [u8; 32],
}

impl PasswordChange {
    /// The operation of the request's proof.
    pub const OP: AuthOp = AuthOp::UnlockMethodPasswordPut;

    /// Signs the request with `sk_a` of `vault` (the vault the change was made
    /// for), for [`PasswordChange::OP`]. `body` is the exact bytes that are
    /// sent.
    ///
    /// Spec: Fase 1 § 4.6.
    pub fn sign(
        &self,
        vault: &UnlockedVault,
        nonce: &[u8; 32],
        body: &[u8],
    ) -> Result<[u8; 64], Error> {
        auth_sign(vault, Self::OP, nonce, body)
    }
}

/// Checks that the pinned record is this vault's, at this epoch.
fn check_pinned_vault(pinned: &Pinned, vault: &UnlockedVault) -> Result<(), Error> {
    pinned.validate()?;
    let ctx = vault.context();
    if pinned.account_id != ctx.account_id {
        return Err(Error::Pinned(PinnedField::AccountId));
    }
    if pinned.vault_id != ctx.vault_id {
        return Err(Error::Pinned(PinnedField::VaultId));
    }
    if pinned.vk_epoch_max != ctx.vk_epoch {
        return Err(Error::Pinned(PinnedField::VkEpoch));
    }
    if pinned.pk_a != vault.auth_public_key() {
        return Err(Error::Pinned(PinnedField::AuthKey));
    }
    Ok(())
}

/// Changes the master password, or upgrades the KSF profile (the same flow
/// with the same password and a higher `profile`; a lower one than the
/// pinned or the current wrap's is [`Error::KdfProfileDowngrade`]).
///
/// The vault key, the item keys and the items are not touched. A new
/// `KEK_pw` comes from the new registration's export key, the password wrap
/// is made again under the same method id with the next generation, and the
/// manifest is made again with that generation (its other entries and
/// unknown keys are kept). The old export key does not open the new wrap.
///
/// * `vault` is the open vault; `pinned` is its device's record (account,
///   vault, epoch and `pk_a` must agree, and the password floor must be
///   seeded);
/// * `current` is the password wrap the server holds; `manifest` is the
///   current manifest row, which must list that wrap;
/// * the registration is checked as described in the module documentation.
///
/// Sign the request with [`PasswordChange::sign`]. After the server has
/// accepted it, the next unlock with the new wrap raises the pinned
/// profile and floor on its own.
///
/// Spec: Fase 1 § 4.2 ("Oppgradering av KSF-profil"), § 4.3 ("Bytte av MP")
/// and § 4.6.
pub fn change_password<R: SecureRng>(
    rng: &mut R,
    vault: &UnlockedVault,
    password: NewPassword<'_>,
    pinned: &Pinned,
    current: &WrapRecord,
    manifest: &ManifestRow<'_>,
) -> Result<PasswordChange, Error> {
    let NewPassword {
        input,
        registration,
        profile,
    } = password;
    let ctx = *vault.context();
    check_pinned_vault(pinned, vault)?;
    check_registration(
        PinState::Pinned(pinned),
        input,
        profile,
        &registration.server_public_key,
    )?;
    let Method::Password { ksf: current_ksf } = &current.method else {
        return Err(Error::Unsupported);
    };
    if profile.number() < current_ksf.number() {
        return Err(Error::KdfProfileDowngrade);
    }

    let old = decrypt_manifest(vault, manifest.rev, manifest.envelope, manifest.tag)?;
    let index = singleton(&old, TYPE_PASSWORD)?;
    let listed = entry_at(&old, index)?;
    if listed.method_id != current.method_id {
        return Err(entries_error());
    }
    let generation = pinned
        .next_generation(&MethodKey::Password)?
        .max(after(listed.kek_generation)?)
        .max(after(current.kek_generation)?);
    let new_rev = manifest.rev.checked_add(1).ok_or_else(entries_error)?;

    let kek = Kek::from_export_key(&ctx.account_id, &registration.export_key)?;
    let wrap = wrap_vk(
        rng,
        &ctx,
        vault.vault_key(),
        &kek,
        current.method_id,
        generation,
        Method::Password { ksf: profile },
    )?;
    let mut new_manifest = old;
    entry_at_mut(&mut new_manifest, index)?.kek_generation = generation;
    let sealed = encrypt_manifest(rng, vault, new_rev, &new_manifest)?;

    check_wrap(&ctx, &kek, &wrap, vault)?;
    if decrypt_manifest(vault, sealed.rev, &sealed.envelope, &sealed.tag)? != new_manifest {
        return Err(Error::Decrypt);
    }
    Ok(PasswordChange {
        registration_record: registration.record,
        ksf_profile: profile,
        wrap,
        manifest: sealed,
        server_public_key: registration.server_public_key,
    })
}

// --------------------------------------------------------------- recover

/// The result of a recovery: the vault, a new password wrap, a **new**
/// recovery key with its wrap and `pk_r`, and a new manifest. It holds
/// secrets (the vault and both recovery keys), so it has no `Clone` and no
/// `Debug`.
pub struct Recovered {
    /// The vault the recovery key opened, in the same epoch.
    pub vault: UnlockedVault,
    /// The new recovery key, to be shown on a new emergency sheet.
    pub recovery_key: RecoveryKey,
    /// The new `pk_r`.
    pub pk_r: [u8; 32],
    /// The new password wrap.
    pub password_wrap: WrapRecord,
    /// The new recovery wrap, under the new recovery key.
    pub recovery_wrap: WrapRecord,
    /// The new manifest, one revision up.
    pub manifest: SealedItem,
    /// The OPAQUE registration record to upload.
    pub registration_record: Vec<u8>,
    /// The KSF profile of the new registration.
    pub ksf_profile: KsfProfile,
    /// Whether the new password input has a secret key. On a device with a
    /// pinned record this equals the pinned bit.
    pub sk_bit: bool,
    /// The OPAQUE server public key the registration showed. It has been
    /// compared with the pinned one when there is one; on a new device
    /// ([`PinState::FirstUse`]) compare it with the one on the emergency
    /// sheet (`SetupQr::server_public_key`) before it is pinned.
    pub server_public_key: [u8; 32],
    /// The recovery key that was used. The request is signed with its `sk_r`
    /// against the `pk_r` the server holds.
    old_recovery_key: RecoveryKey,
}

impl Recovered {
    /// Signs the `recover` request with `sk_r` of the recovery key that
    /// opened the vault. `vk_epoch` in the proof is the vault's current epoch.
    /// `body` is the exact bytes that are sent.
    ///
    /// Spec: Fase 1 § 4.6 and § 6.3 step 4.
    pub fn sign(&self, nonce: &[u8; 32], body: &[u8]) -> Result<[u8; 64], Error> {
        let ctx = self.vault.context();
        recovery_sign(
            &self.old_recovery_key,
            &ctx.account_id,
            ctx.vk_epoch,
            nonce,
            body,
        )
    }
}

/// What a recovery starts from: the recovery key as the user typed it and
/// what the server holds.
#[derive(Clone, Copy)]
pub struct RecoveryInput<'a> {
    /// The account, vault and current epoch of the recovery wrap.
    pub ctx: &'a VaultContext,
    /// The recovery key code as typed (`FFR1-...`).
    pub rk_code: &'a str,
    /// The recovery wrap the server holds.
    pub rk_wrap: &'a WrapRecord,
    /// The current manifest row.
    pub manifest: ManifestRow<'a>,
    /// The id of the new recovery wrap.
    pub new_recovery_method_id: MethodId,
}

/// Recovers an account with the recovery key code `rk_code`.
///
/// 1. The code is read first (prefix, symbols, check and spare bits), before
///    anything else is looked at or drawn.
/// 2. `rk_wrap`, the recovery wrap the server holds, is opened with
///    `KEK_rk`. A wrong key is `decrypt`.
/// 3. The registration (a new master password and secret key choice) is
///    checked as described in the module documentation, with `pin` (a
///    device with a record) or [`PinState::FirstUse`] (a new device). With a
///    record the wrap's epoch, `kek_generation` and the vault's `pk_a` are
///    checked against it as well.
/// 4. A new password wrap (under the same method id as in the manifest), a
///    **new** recovery key with its own wrap (under `new_recovery_method_id`)
///    and `pk_r`, and a new manifest are made. The vault key is unchanged.
///
/// `recovery.manifest` is opened with the recovered
/// vault key and must list one password and one recovery method, the latter
/// being `rk_wrap`. Sign the request with [`Recovered::sign`]; the old
/// recovery key is kept for that and wiped when the value is dropped. The
/// server then replaces `pk_r` and the wraps, and revokes the other
/// sessions. The old recovery key no longer opens anything, but a copy of
/// the old wrap in a backup does: offer a full rekey if the old key was
/// exposed.
///
/// Spec: Fase 1 § 6.3, § 4.5 and § 4.6.
pub fn recover<R: SecureRng>(
    rng: &mut R,
    recovery: &RecoveryInput<'_>,
    password: NewPassword<'_>,
    pin: PinState<'_>,
) -> Result<Recovered, Error> {
    let RecoveryInput {
        ctx,
        rk_code,
        rk_wrap,
        manifest,
        new_recovery_method_id,
    } = *recovery;
    let NewPassword {
        input,
        registration,
        profile,
    } = password;
    // 1. The check symbols, before any KDF or key use.
    let old_recovery_key = decode_recovery_key(rk_code)?;
    if !matches!(rk_wrap.method, Method::Recovery) {
        return Err(Error::Unsupported);
    }

    // 2. The vault.
    let old_kek = Kek::from_recovery_key(&ctx.account_id, &old_recovery_key)?;
    let vault = unwrap_vk(ctx, &old_kek, rk_wrap)?;

    // 3. The pins and the registration.
    check_registration(pin, input, profile, &registration.server_public_key)?;
    let mut password_floor = None;
    let mut recovery_floor = None;
    if let PinState::Pinned(pinned) = pin {
        if pinned.account_id != ctx.account_id {
            return Err(Error::Pinned(PinnedField::AccountId));
        }
        if pinned.vault_id != ctx.vault_id {
            return Err(Error::Pinned(PinnedField::VaultId));
        }
        if ctx.vk_epoch < pinned.vk_epoch_max {
            return Err(Error::Pinned(PinnedField::VkEpoch));
        }
        if ctx.vk_epoch == pinned.vk_epoch_max && vault.auth_public_key() != pinned.pk_a {
            return Err(Error::Pinned(PinnedField::AuthKey));
        }
        password_floor = pinned.floor(&MethodKey::Password);
        recovery_floor = pinned.floor(&MethodKey::Recovery);
        if recovery_floor.is_some_and(|floor| rk_wrap.kek_generation < floor) {
            return Err(Error::Pinned(PinnedField::KekGeneration));
        }
    }

    // 4. The manifest and the generations.
    let old = decrypt_manifest(&vault, manifest.rev, manifest.envelope, manifest.tag)?;
    let password_index = singleton(&old, TYPE_PASSWORD)?;
    let recovery_index = singleton(&old, TYPE_RECOVERY)?;
    let password_entry = entry_at(&old, password_index)?;
    let recovery_entry = entry_at(&old, recovery_index)?;
    if recovery_entry.method_id != rk_wrap.method_id {
        return Err(entries_error());
    }
    let password_method_id = password_entry.method_id;
    let mut password_generation = after(password_entry.kek_generation)?;
    if let Some(floor) = password_floor {
        password_generation = password_generation.max(after(floor)?);
    }
    let mut recovery_generation =
        after(recovery_entry.kek_generation)?.max(after(rk_wrap.kek_generation)?);
    if let Some(floor) = recovery_floor {
        recovery_generation = recovery_generation.max(after(floor)?);
    }
    let new_rev = manifest.rev.checked_add(1).ok_or_else(entries_error)?;

    // 5. The new wraps, the new recovery key and the manifest.
    let password_kek = Kek::from_export_key(&ctx.account_id, &registration.export_key)?;
    let password_wrap = wrap_vk(
        rng,
        ctx,
        vault.vault_key(),
        &password_kek,
        password_method_id,
        password_generation,
        Method::Password { ksf: profile },
    )?;
    let recovery_key = RecoveryKey::generate(rng);
    let recovery_kek = Kek::from_recovery_key(&ctx.account_id, &recovery_key)?;
    let recovery_wrap = wrap_vk(
        rng,
        ctx,
        vault.vault_key(),
        &recovery_kek,
        new_recovery_method_id,
        recovery_generation,
        Method::Recovery,
    )?;
    let pk_r = recovery_public_key(&recovery_key, &ctx.account_id)?;
    let mut new_manifest = old;
    {
        let entry = entry_at_mut(&mut new_manifest, password_index)?;
        entry.kek_generation = password_generation;
    }
    {
        let entry = entry_at_mut(&mut new_manifest, recovery_index)?;
        entry.method_id = new_recovery_method_id;
        entry.kek_generation = recovery_generation;
    }
    let sealed = encrypt_manifest(rng, &vault, new_rev, &new_manifest)?;

    check_wrap(ctx, &password_kek, &password_wrap, &vault)?;
    check_wrap(ctx, &recovery_kek, &recovery_wrap, &vault)?;
    if decrypt_manifest(&vault, sealed.rev, &sealed.envelope, &sealed.tag)? != new_manifest {
        return Err(Error::Decrypt);
    }

    Ok(Recovered {
        vault,
        recovery_key,
        pk_r,
        password_wrap,
        recovery_wrap,
        manifest: sealed,
        registration_record: registration.record,
        ksf_profile: profile,
        sk_bit: input.includes_secret_key(),
        server_public_key: registration.server_public_key,
        old_recovery_key,
    })
}

// ----------------------------------------------------------- confirmation

/// The confirmation of the recovery key at setup: reads the code the user
/// typed in full, **opens the recovery wrap with it** and compares the vault
/// key it holds with the one of `expected`, in constant time. The setup is
/// not finished until this succeeds.
///
/// A typo is `checksum` (or `non_canonical`, `malformed_code`) before any key
/// is used; a correct code for another key is `decrypt`. `rk_wrap` must be a
/// recovery wrap (`unsupported` otherwise).
///
/// Spec: Fase 1 § 6.1 ("Bekreftelse ved oppsett").
pub fn verify_recovery_setup(
    entered_rk: &str,
    rk_wrap: &WrapRecord,
    expected: &UnlockedVault,
) -> Result<(), Error> {
    let rk = decode_recovery_key(entered_rk)?;
    if !matches!(rk_wrap.method, Method::Recovery) {
        return Err(Error::Unsupported);
    }
    let ctx = expected.context();
    let kek = Kek::from_recovery_key(&ctx.account_id, &rk)?;
    let opened = unwrap_vk(ctx, &kek, rk_wrap)?;
    if opened.same_vault_key(expected) {
        Ok(())
    } else {
        Err(Error::Decrypt)
    }
}

/// The confirmation of the secret key at setup: reads the code the user typed
/// and compares it with the secret key that was made, in constant time. A
/// typo is `checksum` (or `non_canonical`, `malformed_code`); a correct code
/// for another key is `decrypt`.
///
/// Spec: Fase 1 § 6.1 ("Bekreftelse ved oppsett"), § 6.2.
pub fn verify_secret_key_entry(entered: &str, expected: &SecretKey) -> Result<(), Error> {
    let sk = decode_secret_key(entered)?;
    if bool::from(subtle::ConstantTimeEq::ct_eq(&sk, expected)) {
        Ok(())
    } else {
        Err(Error::Decrypt)
    }
}
