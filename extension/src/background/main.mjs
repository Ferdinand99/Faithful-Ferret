// The entry of the background page (MV3 `background.scripts`, MV2 `background.html`).
//
// It wires the modules and puts nothing on `globalThis`: the core host (the
// only holder of the WASM client, and so of any key), the account session, the
// sync, the matching and the popup's item operations that run in it (their
// operations are the core host's), the clipboard, the lock and the router; and
// the keyboard shortcut and the context menu, which reach the vault only
// through the core host's fill operations.
// The sync engine stays inside the sync (sync.mjs): the matching and the item
// operations get its items to read, never the engine.
// The forms the user submitted are held by the capture host (captureHost.mjs): the store of offers, the registration
// of the capture script and the setting; only in a build with saving passwords on, and only in memory. The toolbar
// button's badge (badge.mjs) shows how many offers a tab has, and the popup opens by itself where that is allowed
// (autoOpen.mjs).
// Every listener is registered while the module loads, so the event that woke
// the page reaches it.
//
// The background page starts locked. If it dies, the next start is locked too:
// the keys lived in the page and went with it.

import { createAutoOpen } from "./autoOpen.mjs";
import { createBadge } from "./badge.mjs";
import { createCaptureHost } from "./captureHost.mjs";
import { createClipboard } from "./clipboard.mjs";
import { createHttpsAccess } from "./httpsAccess.mjs";
import { createQuickFill, listenForCommands } from "./commands.mjs";
import { action } from "./compat.mjs";
import { createCoreHost, defaultCreateClient } from "./coreHost.mjs";
import { createFillContext } from "./fillContext.mjs";
import { createFillHost } from "./fillFlow.mjs";
import { createCandidateSource } from "./frames.mjs";
import { createGeneratorHost } from "./generator.mjs";
// @ts-ignore -- generated by the build from handlers/*.handler.mjs
import { HANDLERS } from "./handlers.gen.mjs";
import { createLock } from "./lock.mjs";
import { createMatchHost } from "./match.mjs";
import { labelLanguage } from "./offerWrite.mjs";
import { removePasskeyScripts } from "./passkeyCleanup.mjs";
// @ts-ignore -- generated by the build: the modules of Ferret as a passkey provider when the feature is on, null when it is off
import { chooserWindows, createPasskeyNever, createPasskeyRegistry, createPasskeyRequests, createPasskeySettings, PASSKEY_WINDOW_PAGE } from "./passkeys.gen.mjs";
import { createPinHost } from "./pinHost.mjs";
import { listenForMenus, menuTitle } from "./menus.mjs";
import { createRouter } from "./router.mjs";
import { createSessionHost } from "./session.mjs";
import { createSyncHost } from "./sync.mjs";
import { deleteUnlockDatabase } from "./unlockCleanup.mjs";
// @ts-ignore -- generated by the build: the PIN store when the unlock feature is on, null when it is off
import { createLocalUnlock as createPinStore, UNLOCK_WINDOW_PAGE } from "./unlockStore.gen.mjs";
// @ts-ignore -- generated by the build: what differs between the variants
import { variantHooks } from "./variant.gen.mjs";
import { FEATURES } from "../shared/features.mjs";

const runtime = browser.runtime;
const now = () => Date.now();
/** @type {any} */
const hooks = variantHooks;

// The test build signs in against its test stacks, whose names a release refuses.
const sessionHost = createSessionHost({
  storageLocal: browser.storage.local,
  permissions: { contains: (wanted) => browser.permissions.contains(wanted) },
  platformInfo: () => runtime.getPlatformInfo(),
  allowTestHosts: variantHooks !== null,
  now,
});

// The PIN (the flag `unlock`): its store, which only the generated module reaches, and its host. A build with the flag off
// has neither: the PIN's operations are not registered and its messages are refused.
const pinStore = createPinStore
  ? createPinStore({ idb: globalThis.indexedDB, session: browser.storage.session, now })
  : null;
const pinHost = pinStore
  ? createPinHost({ store: pinStore, sessionHost, alarms: browser.alarms, now, windows: browser.windows, getURL: (path) => runtime.getURL(path), windowPage: UNLOCK_WINDOW_PAGE })
  : null;

// What Ferret filled where, for a change form submitted afterwards (memory only, cleared at every lock); only with
// saving passwords, a build feature (the flag `save`, on in a release).
const fillContext = FEATURES.save ? createFillContext({ now }) : null;
// The popup's offer of a one-time code after a sign-in was filled does not depend on saving passwords: without the flag the
// fill flow keeps its own memory of what it filled (item ids, five minutes, cleared at every lock), which nothing else reads.
const codeOfferContext = fillContext ?? createFillContext({ now });

// The capture host (the store of offers, the registration of the capture script, the setting); only with saving passwords.
// The sync and the capture host need each other (the sync reads the offers it writes, the store asks the sync whether a
// login is saved already), so each reaches the other through a function.
/** @type {ReturnType<typeof createCaptureHost> | null} */
let captureHost = null;

// The sync engine starts when the session opens the vault and stops at every lock. The offers to save a password come
// from the capture host's store of offers (and, in the test build, from what its hooks planted).
const syncHost = createSyncHost({
  sessionHost,
  permissions: { remove: (gone) => browser.permissions.remove(gone) },
  captures: {
    peek: (offerId, session) => captureHost?.offers.peek(offerId, session) ?? hooks?.captures?.peek(offerId, session) ?? null,
    take: (offerId, session) => captureHost?.offers.take(offerId, session) ?? hooks?.captures?.take(offerId, session) ?? null,
  },
  fillContext,
  // The web vault's languages: Norwegian for a Norwegian browser, English otherwise.
  language: labelLanguage(navigator.languages ?? [navigator.language]),
  // The test build's hooks make test items with the engine of the open vault, so they make it; a release has no hooks,
  // and there the engine is made and kept by the sync alone.
  ...(hooks?.createEngine ? { createEngine: hooks.createEngine } : {}),
});

// The popup that opens by itself and the badge on the toolbar button (only with saving passwords). The badge tells the
// popup's opener when a tab gets its first offer; the opener asks the core host whether the vault is open.
/** @type {any} */
let coreHostForOpen = null;
const autoOpen = FEATURES.save
  ? createAutoOpen({
      storageLocal: browser.storage.local,
      action,
      tabs: browser.tabs,
      windows: browser.windows,
      unlocked: () => coreHostForOpen?.state() === "unlocked",
      popupOpen: () => (browser.extension.getViews({ type: "popup" })?.length ?? 0) > 0,
    })
  : null;
// The badge also carries the passkey mark (a request that waits for the user outside Ferret's window).
const badge = FEATURES.save || FEATURES.passkeys ? createBadge({ action, now, onAppear: (tabId) => void autoOpen?.maybeOpen(tabId) }) : null;

// The permission for https pages is shared by saving passwords and the passkeys: a grant never switches a feature on by itself, and
// turning one feature off takes the permission back only when the other does not need it (httpsAccess.mjs).
const httpsAccess = createHttpsAccess({ permissions: browser.permissions, storageLocal: browser.storage.local, now, features: FEATURES });

captureHost = FEATURES.save
  ? createCaptureHost({
      now,
      random: (bytes) => globalThis.crypto.getRandomValues(/** @type {Uint8Array<ArrayBuffer>} */ (bytes)),
      webNavigation: browser.webNavigation,
      tabs: browser.tabs,
      scripting: browser.scripting,
      permissions: browser.permissions,
      storageLocal: browser.storage.local,
      badge,
      autoOpen,
      writer: { classify: (capture) => syncHost.classifyCapture(capture) },
      access: httpsAccess,
    })
  : null;

// Ferret as a passkey provider (the flag `passkeys`): the registration of the scripts in web pages (registered exactly when
// the setting is on, the permission for https pages is there and the extension is signed in; reconciled at every start,
// which an install or an update also is, when the permission or the server changes, and by the settings' switch) and the
// background's side of the bridge, the request broker. Only listeners that the browser wakes the page for rarely: no
// storage listener (it kept a Manifest V3 event page from stopping), and the broker's navigation, tab and window listeners
// only while a request waits (added after the first turn, they never wake the page). A build with the flag off has neither
// (the generated module says null) and only removes what an earlier build registered (below).
/** @type {any} */
let passkeyRequests = null;
const passkeyListeners = {
  committed: (/** @type {any} */ details) => passkeyRequests?.onNavigation(details),
  sameDocument: (/** @type {any} */ details) => passkeyRequests?.onSameDocument(details),
  tabRemoved: (/** @type {number} */ tabId) => passkeyRequests?.onTabRemoved(tabId),
  windowRemoved: (/** @type {number} */ windowId) => passkeyRequests?.onWindowRemoved(windowId),
};
/** The "never on this site" list: one, shared by the broker and the settings (it keeps what it read in memory). */
const passkeyNever = createPasskeyNever ? createPasskeyNever({ storageLocal: browser.storage.local }) : null;
/** The broker's events and their listeners, each added on its own (a browser without one of the events still gets the others). */
const passkeyEvents = () =>
  /** @type {Array<[any, (...args: any[]) => void]>} */ ([
    [browser.webNavigation?.onCommitted, passkeyListeners.committed],
    [browser.webNavigation?.onHistoryStateUpdated, passkeyListeners.sameDocument],
    [browser.webNavigation?.onReferenceFragmentUpdated, passkeyListeners.sameDocument],
    [browser.tabs?.onRemoved, passkeyListeners.tabRemoved],
    [browser.windows?.onRemoved, passkeyListeners.windowRemoved],
  ]);
passkeyRequests = createPasskeyRequests
  ? createPasskeyRequests({
      tabs: browser.tabs,
      frames: browser.webNavigation,
      // The chooser window, when the package has its page.
      windows: PASSKEY_WINDOW_PAGE ? chooserWindows({ windows: browser.windows, getURL: (/** @type {string} */ path) => runtime.getURL(path), page: PASSKEY_WINDOW_PAGE }) : null,
      badge,
      // The signed-in server, and whether its device session is live (a device ended remotely keeps its server).
      servers: {
        current: async () => {
          const server = await sessionHost.storedServer();
          if (server === null) return null;
          const state = await sessionHost
            .sessionFor(server)
            .then((session) => session.deviceState())
            .catch(() => null);
          return { origin: server, live: state === "ok" };
        },
      },
      storageLocal: browser.storage.local,
      permissions: browser.permissions,
      // "Never on this site" (the chooser window's choice): the broker asks it before a window opens and adds to it; the settings list
      // and remove from the same one.
      never: passkeyNever,
      // The one-time pass of "use the browser" outlives a stopped event page (session storage: in memory, gone when the browser closes).
      passStorage: browser.storage.session,
      listen: {
        start() {
          for (const [event, listener] of passkeyEvents()) {
            try {
              event.addListener(listener);
            } catch {
              // This browser has no such event: the others still run.
            }
          }
        },
        stop() {
          for (const [event, listener] of passkeyEvents()) {
            try {
              event.removeListener(listener);
            } catch {
              // Nothing to remove.
            }
          }
        },
      },
      // A release leaves localhost and the loopback addresses to the browser; the test build keeps https://localhost.
      release: variantHooks === null,
      now,
    })
  : null;
const passkeyRegistry = createPasskeyRegistry
  ? createPasskeyRegistry({
      scripting: browser.scripting,
      permissions: browser.permissions,
      storageLocal: browser.storage.local,
      // A release leaves localhost to the browser; the test build keeps it for its fixtures.
      release: variantHooks === null,
      access: httpsAccess,
    })
  : null;
// The settings of the provider: the switch (through the registry), the "never" list and the recent-unlock choice.
const passkeySettings = createPasskeySettings && passkeyRegistry && passkeyNever ? createPasskeySettings({ registry: passkeyRegistry, never: passkeyNever, storageLocal: browser.storage.local }) : null;
if (passkeyRegistry) {
  browser.permissions.onAdded?.addListener((/** @type {any} */ added) => {
    passkeyRegistry.onPermissionAdded(added).catch(() => {});
  });
  browser.permissions.onRemoved?.addListener((/** @type {any} */ removed) => {
    passkeyRegistry.onPermissionRemoved(removed).catch(() => {});
  });
  // A sign-in stores the server, "forget this server" removes it.
  sessionHost.onServerChange(() => {
    passkeyRegistry.reconcile().catch(() => {});
    // A sign-in or "forget this server" (also while the vault is locked): every request was checked against the server
    // that was there, so none of them goes on.
    passkeyRequests?.endAll();
  });
}

// Ferret's copies: the background writes the clipboard itself, and clears it 30 seconds later (its alarm listener is
// registered now, so the alarm that wakes an unloaded page reaches it).
const clipboard = createClipboard({
  writeText: (text) => navigator.clipboard.writeText(text),
  storageSession: browser.storage.session,
  alarms: browser.alarms,
  now,
});

// The matching opens the items of the sync engine's list in the core host, and nowhere else.
// (The sync's `items()`: the engine's `list` and `open`, nothing that writes.)
const matchHost = createMatchHost({ engine: () => /** @type {any} */ (syncHost.items()) });

// The generated password the popup shows and fills (memory only, until the next lock or 15 minutes); only with saving
// passwords, a build feature (the flag `save`, on in a release). Nothing in it makes a password: the core does.
const generatorHost = FEATURES.save
  ? createGeneratorHost({
      now,
      newId: () => Array.from(globalThis.crypto.getRandomValues(new Uint8Array(16)), (b) => b.toString(16).padStart(2, "0")).join(""),
      clipboard,
    })
  : null;

/** @type {any} */
let coreHostRef = null;
// The list, search, copy and "Fill" of the popup, over the page matching of the tab's frames (frames.mjs): the frames
// from the browser, the site rules and the match from the core.
const fillHost = createFillHost({
  // The engine's list and items (the sync's `items()`; the sync engine is the web vault's, typed there).
  syncHost: { engine: () => /** @type {any} */ (syncHost.items()) },
  fillContext: codeOfferContext,
  generator: generatorHost,
  // A generated password that went into a page is offered for saving by the capture host's store of offers.
  offers: captureHost !== null ? { onGenerated: (meta) => /** @type {NonNullable<typeof captureHost>} */ (captureHost).offers.onGenerated(meta) } : null,
  clipboard,
  scripting: browser.scripting,
  tabs: browser.tabs,
  source: createCandidateSource({
    webNavigation: browser.webNavigation,
    permissions: { contains: (wanted) => browser.permissions.contains(wanted) },
    call: (op, args) => coreHostRef.call(op, args),
  }),
  now,
});

const coreHost = createCoreHost({
  createClient: defaultCreateClient,
  now,
  timers: {
    setTimeout: (fn, ms) => setTimeout(fn, ms),
    clearTimeout: (id) => clearTimeout(/** @type {any} */ (id)),
  },
  ops: { ...sessionHost.ops, ...syncHost.ops, ...matchHost.ops, ...fillHost.ops, ...(captureHost?.ops ?? {}), ...(generatorHost?.ops ?? {}), ...(pinHost?.ops ?? {}), ...(passkeyRequests?.ops ?? {}), ...(passkeySettings?.ops ?? {}) },
});
coreHostRef = coreHost;
coreHostForOpen = coreHost;
sessionHost.attach(coreHost);
// A lock of the open vault ends every passkey request that waits (and every mark of verification goes at every lock). A lock
// of a vault that was locked already (a wrong PIN in Ferret's window) ends nothing.
if (passkeyRequests) {
  let vaultOpen = false;
  coreHost.onUnlocked(() => {
    vaultOpen = true;
  });
  coreHost.onLocked(() => {
    const wasOpen = vaultOpen;
    vaultOpen = false;
    passkeyRequests.onLock(wasOpen);
  });
}
syncHost.attach(coreHost);
matchHost.attach(coreHost);
fillHost.attach(coreHost);
captureHost?.attach(coreHost);
generatorHost?.attach(coreHost);
pinHost?.attach(coreHost);

const lock = createLock({
  alarms: browser.alarms,
  idle: browser.idle,
  storageSession: browser.storage.session,
  storageLocal: browser.storage.local,
  now,
  coreHost,
});

// The deadline is also checked before every use of the vault by the modules that work beside the messages (the sync).
coreHost.setGuard(() => lock.isDue());

const router = createRouter({
  runtime,
  lock,
  coreHost,
  handlers: /** @type {readonly import("./router.mjs").Handler[]} */ (HANDLERS),
  // The references a page got end with its port.
  onSessionEnd: (session) => {
    fillHost.endSession(session);
    syncHost.endSession(session);
    captureHost?.endSession(session);
    // The chooser window that owned a passkey request is gone: the request ends as cancelled.
    passkeyRequests?.endSession(session);
  },
});

runtime.onConnect.addListener(router.onConnect);
runtime.onMessage.addListener(router.onMessage);

// The shortcut and the context menu: one match fills, anything else opens the popup. They reach the vault only
// through the core host's fill operations.
const quickFill = createQuickFill({
  coreHost,
  lock,
  // The fill flow's references of each action end with it.
  sessions: fillHost,
  openPopup: () => action.openPopup(),
  // A fill the shortcut or the menu tried and that was refused: the badge shows "!" and the popup says why.
  onRefused: badge === null ? null : (tabId, reason) => badge.refuse(tabId, reason),
  scripting: browser.scripting,
  webNavigation: browser.webNavigation,
});
listenForCommands({ commands: browser.commands, quickFill });
listenForMenus({
  menus: browser.menus,
  quickFill,
  title: menuTitle({
    fetch: (url) => fetch(url),
    getURL: (path) => runtime.getURL(path),
    languages: navigator.languages ?? [navigator.language],
  }),
});

// Only the test build has hooks, and they are set up here, in the first turn of the
// page, so a port or an alarm that woke the page reaches them. `variantHooks` is null
// in a release, so a release has no test code to run.
if (hooks) {
  hooks.install({ browser, runtime, coreHost, now, offers: captureHost?.offers ?? null, engine: () => (syncHost.items() !== null ? hooks.engine() : null), passkeys: passkeyRegistry });
}

// A new page has no vault, whatever an earlier page left in `storage.session`.
coreHost.lock("restart").catch(() => {});

// A build with PIN and passkey unlock off opens no PIN store; it only removes the one an earlier build may have left.
if (!FEATURES.unlock) void deleteUnlockDatabase(globalThis.indexedDB);
// A build with Ferret as a passkey provider off registers no script in pages; it removes the ones that an earlier build left.
if (!FEATURES.passkeys) void removePasskeyScripts(browser.scripting, browser.storage.local, httpsAccess);
// With it on, the registration is made to agree with the setting, the permission and the sign-in.
passkeyRegistry?.reconcile().catch(() => {});
// With it on, the PIN host starts its schedule (the renewal of the device's tokens, with or without a PIN).
pinHost?.start();
